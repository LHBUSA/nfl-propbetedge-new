create or replace function public.nfl_prop_official_requires_trained()
returns trigger
language plpgsql
as $$
declare
  v_ok boolean;
begin
  if new.publication_scope <> 'official' then return new; end if;
  select (m.promoted = true and m.trained = true)
    into v_ok
    from public.nfl_prop_selector_models m
   where m.version = new.selector_version
     and m.market = new.market;
  if coalesce(v_ok, false) <> true then
    raise exception 'official player-prop pick requires promoted trained selector';
  end if;
  return new;
end
$$;

