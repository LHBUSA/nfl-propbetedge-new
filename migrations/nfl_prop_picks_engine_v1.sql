after insert on public.nfl_prop_picks
for each row execute function public.nfl_prop_receipt_after_insert();

create or replace function public.nfl_replace_open_prop_pick(
  p_open_id uuid,
  p_event_id text,
  p_season integer,
  p_week integer,
  p_kickoff_ts timestamptz,
  p_player_name text,
  p_player_key text,
  p_market text,
  p_side text,
  p_book text,
  p_book_key text,
  p_market_line numeric,
  p_market_price integer,
  p_opposite_price integer,
  p_model_fair_line numeric,
  p_predictive_sd numeric,
  p_model_prob numeric,
  p_market_prob numeric,
  p_edge_pct numeric,
  p_ev_pct numeric,
  p_stake_units numeric,
  p_confidence_bucket text,
  p_projection_model_version text,
  p_selector_version bigint,
  p_phase text,
  p_publication_scope text,
  p_model_snapshot jsonb
) returns uuid
language plpgsql
security definer
as $$
declare
  v_new_id uuid;
begin
  update public.nfl_prop_picks
     set status = 'superseded', closed_at = now()
   where id = p_open_id and status = 'open';
  if not found then raise exception 'open prop pick not found'; end if;

  insert into public.nfl_prop_picks (
    event_id, season, week, kickoff_ts, player_name, player_key,
    market, side, book, book_key, market_line, market_price, opposite_price,
    model_fair_line, predictive_sd, model_prob, market_prob, edge_pct, ev_pct,
    stake_units, confidence_bucket, projection_model_version, selector_version,
    phase, publication_scope, status, model_snapshot
  ) values (
    p_event_id, p_season, p_week, p_kickoff_ts, p_player_name, p_player_key,
    p_market, p_side, p_book, p_book_key, p_market_line, p_market_price, p_opposite_price,
    p_model_fair_line, p_predictive_sd, p_model_prob, p_market_prob, p_edge_pct, p_ev_pct,
    p_stake_units, p_confidence_bucket, p_projection_model_version, p_selector_version,
    p_phase, p_publication_scope, 'open', p_model_snapshot
  ) returning id into v_new_id;

  return v_new_id;
end
$$;

