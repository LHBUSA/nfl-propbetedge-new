-- PropBetEdge NFL Player Prop Engine v1
--
-- Algorithm #2 is intentionally separate from the game-market picker.
-- v1 supports the production passing-yards projection model only. The schema
-- is market-extensible, but unsupported markets must not be synthesized.
--
-- Invariants:
--   * every issued decision freezes player / market / book / line / price,
--     projection distribution, selector version and model snapshot;
--   * bootstrap tracking decisions can never be reclassified as official;
--   * official issuance requires a promoted + trained selector champion;
--   * one open decision per event/player/market; replacements are atomic;
--   * receipt ledger is append-only and chained with SHA-256;
--   * RLS is enabled with no anon policies. Service role only.

begin;

